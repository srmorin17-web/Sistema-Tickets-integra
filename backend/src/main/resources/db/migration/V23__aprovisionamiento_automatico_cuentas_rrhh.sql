CREATE TABLE usuario.provisionamiento_config (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    automatico BOOLEAN NOT NULL DEFAULT FALSE,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO usuario.provisionamiento_config (id, automatico)
VALUES (1, FALSE);

CREATE TABLE usuario.provisionamiento_cola (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado UUID NOT NULL REFERENCES empleado.empleado(id) ON DELETE CASCADE,
    origen VARCHAR(12) NOT NULL CHECK (origen IN ('AUTOMATICO', 'MASIVO')),
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'PROCESANDO', 'COMPLETADO', 'FALLIDO')),
    resultado VARCHAR(12),
    intentos SMALLINT NOT NULL DEFAULT 0,
    ultimo_error VARCHAR(500),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_provisionamiento_empleado UNIQUE (id_empleado)
);

CREATE INDEX idx_provisionamiento_cola_pendiente
    ON usuario.provisionamiento_cola (id)
    WHERE estado = 'PENDIENTE';
